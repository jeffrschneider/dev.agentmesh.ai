// build-platform-agents.mjs — write the agent list on platform-agents.html
// from the platform-agent registry in the AgentMesh repo.
//
// Usage: node tools/build-platform-agents.mjs [path-to-platform-agent-registry.ts]
// Default source: ../AgentMesh/services/src/api/platform-agent-registry.ts
//
// The registry is the one place a platform agent is declared, so it is also
// the source of this list: add an agent there and it appears here, and there
// is no second list to keep in step. Only the three public fields are read
// (group, blurb, reach) plus the name. The scores stay where they are; they
// are for the operator console, not for a public page.
//
// The generated block is delimited in the HTML. Everything outside it is
// hand-written and this script leaves it alone. Run it whenever the registry
// changes, and commit the page: deploy.sh ships committed files only.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC =
  process.argv[2] ??
  resolve(ROOT, "../AgentMesh/services/src/api/platform-agent-registry.ts");
const PAGE = resolve(ROOT, "platform-agents.html");

const BEGIN = "<!-- BEGIN generated by tools/build-platform-agents.mjs -->";
const END = "<!-- END generated -->";

/** The parts of the list, in the order they are printed, with the heading
 *  and the line that says what the part is. */
const GROUPS = [
  {
    id: "message",
    heading: "Agents you can message",
    line: "These answer requests. Address them the way you address any other agent on the mesh.",
  },
  {
    id: "channel",
    heading: "Channels you can read",
    line: "These publish. You subscribe to them, and they do not answer requests.",
  },
  {
    id: "behind",
    heading: "Agents that work behind the product",
    line: "These run for the product rather than for a person, so there is usually nothing to address.",
  },
];

const src = readFileSync(SRC, "utf8").replace(/\r\n/g, "\n");
const body = src.slice(src.indexOf("export const PLATFORM_AGENTS"));
if (body.length < 100) throw new Error(`no PLATFORM_AGENTS in ${SRC}`);

// One entry is `  key: {` ... `  },` at two spaces of indent; everything
// nested inside it is indented further, so the first two-space close is the
// entry's own. The closing newline is left unconsumed: entries that sit back
// to back need it to open the next match.
const entries = [...body.matchAll(/\n {2}"?([\w-]+)"?: \{\n([\s\S]*?)\n {2}\},(?=\n)/g)];
if (entries.length === 0) throw new Error("parsed no agents: has the registry's shape changed?");

const field = (block, name, id) => {
  const m = block.match(new RegExp(`\\n {4}${name}:\\s*\\n?\\s*"((?:[^"\\\\]|\\\\.)*)"`));
  // A missing public field is a build failure here and a failing test in the
  // AgentMesh repo. Silently dropping an agent from the list is the one
  // outcome this script must never have.
  if (!m) throw new Error(`${id}: no ${name} in the registry. Every platform agent needs one.`);
  return m[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\");
};

const agents = entries.map(([, id, raw]) => {
  // The capture starts after the entry's own newline; put one back so every
  // field matches on the same line shape.
  const block = "\n" + raw;
  return {
    id,
    name: field(block, "name", id),
    group: field(block, "group", id),
    blurb: field(block, "blurb", id),
    reach: field(block, "reach", id),
  };
});

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const em = agents.find((a) => /—/.test(a.blurb + a.reach));
if (em) throw new Error(`${em.id}: em dash in public copy, which the site forbids.`);

let out = "";
for (const g of GROUPS) {
  // Alphabetical inside a part: a directory, not a ranking.
  const rows = agents.filter((a) => a.group === g.id).sort((a, b) => a.name.localeCompare(b.name));
  if (rows.length === 0) continue;
  out += `          <h3>${esc(g.heading)}</h3>\n`;
  out += `          <p>${esc(g.line)}</p>\n`;
  out += `          <table class="tbl">\n            <thead><tr><th>Agent</th><th>What it does</th><th>How to reach it</th></tr></thead>\n            <tbody>\n`;
  for (const a of rows) {
    out += `              <tr><td>${esc(a.name)}</td><td>${esc(a.blurb)}</td><td>${esc(a.reach)}</td></tr>\n`;
  }
  out += `            </tbody>\n          </table>\n`;
}

const page = readFileSync(PAGE, "utf8");
const i = page.indexOf(BEGIN);
const j = page.indexOf(END);
if (i < 0 || j < 0) throw new Error(`platform-agents.html has no generated block`);
writeFileSync(PAGE, page.slice(0, i + BEGIN.length) + "\n" + out + "          " + page.slice(j), "utf8");
console.log(`platform-agents.html: ${agents.length} agents from ${SRC}`);
