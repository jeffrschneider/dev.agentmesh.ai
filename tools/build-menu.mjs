// Writes the left menu (tools/menu.mjs) into every hand-written page, marks
// the page's own entry, and makes sure the page loads the shared theme.css
// and theme.js. Run from the repo root: node tools/build-menu.mjs
// Pages written by the platform-services generator are skipped: they copy the
// menu from platform-map.html when they are regenerated.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { MENU, BEGIN, END, renderMenu } from "./menu.mjs";

const HEAD = '  <link rel="stylesheet" href="theme.css">\n  <script src="theme.js"></script>\n';
const known = new Set(MENU.flatMap(([, items]) => items.map(([href]) => href)));
let changed = 0;
for (const file of readdirSync(".").filter((f) => f.endsWith(".html")).sort()) {
  const src = readFileSync(file, "utf8");
  if (src.includes("GENERATED by node platform-services/gen.mjs")) continue;
  const current = file === "index.html" ? "" : file;
  let out = src;
  const a = out.indexOf(BEGIN);
  if (a >= 0) {
    const b = out.indexOf(END, a);
    if (b < 0) throw new Error(`${file}: menu BEGIN without END`);
    out = out.slice(0, a) + renderMenu(current) + out.slice(b + END.length);
  } else {
    const m = out.match(/[ \t]*<aside class="rail">[\s\S]*?<\/aside>/);
    if (!m) continue; // redirect stubs and the verification file have no menu
    out = out.slice(0, m.index) + "    " + renderMenu(current) + out.slice(m.index + m[0].length);
  }
  if (!out.includes('href="theme.css"')) out = out.replace(/<\/head>/, HEAD + "</head>");
  if (current && !known.has(current)) console.warn(`note: ${file} has no entry in the menu`);
  if (out !== src) { writeFileSync(file, out); changed++; }
}
console.log(`menu written; ${changed} page(s) changed`);
